import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { copyFileSync, existsSync } from "fs";

// Set OBSIDIAN_VAULT env var to auto-sync built files to your vault.
// Example: OBSIDIAN_VAULT="C:/Users/you/Vault" npm run build
const VAULT_PLUGIN_DIR = process.env.OBSIDIAN_VAULT
  ? `${process.env.OBSIDIAN_VAULT}/.obsidian/plugins/obsidian-diary-bot`
  : "";

function syncToVault() {
  if (!VAULT_PLUGIN_DIR || !existsSync(VAULT_PLUGIN_DIR)) return;
  for (const f of ["main.js", "manifest.json", "styles.css"]) {
    if (existsSync(f)) {
      copyFileSync(f, `${VAULT_PLUGIN_DIR}/${f}`);
    }
  }
  console.log(`[esbuild] synced to vault: ${VAULT_PLUGIN_DIR}`);
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE.
Do not edit directly. See src/main.ts.
*/`;

const prod = process.argv[2] === "production";

const ctx = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  platform: "node",
});

if (prod) {
  await ctx.rebuild();
  await ctx.dispose();
  syncToVault();
} else {
  await ctx.watch();
  syncToVault();
}
