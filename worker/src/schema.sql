-- Diary Bot D1 schema. Apply once with:
--   wrangler d1 execute diary-bot-db --file=src/schema.sql --remote

CREATE TABLE IF NOT EXISTS entities (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('person', 'place', 'project')),
  aliases TEXT NOT NULL DEFAULT '[]',  -- JSON array of strings
  first_seen TEXT NOT NULL,            -- YYYY-MM-DD
  last_seen TEXT NOT NULL,
  mention_count INTEGER NOT NULL DEFAULT 0,
  UNIQUE(user_id, name, type)
);
CREATE INDEX IF NOT EXISTS idx_entities_user_lastseen ON entities(user_id, last_seen DESC);
CREATE INDEX IF NOT EXISTS idx_entities_user_name ON entities(user_id, name);

CREATE TABLE IF NOT EXISTS mentions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  entity_id INTEGER NOT NULL,
  user_id TEXT NOT NULL,
  date TEXT NOT NULL,                  -- YYYY-MM-DD
  entry_path TEXT,                     -- e.g. Journal/2026/05/2026-05-01.md
  mood TEXT,
  FOREIGN KEY (entity_id) REFERENCES entities(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_mentions_entity_date ON mentions(entity_id, date DESC);
CREATE INDEX IF NOT EXISTS idx_mentions_user_date ON mentions(user_id, date DESC);

-- Co-occurrence edges for people graph (which entities appeared together on same date).
CREATE TABLE IF NOT EXISTS cooccurrences (
  user_id TEXT NOT NULL,
  entity_a_id INTEGER NOT NULL,
  entity_b_id INTEGER NOT NULL,
  weight INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (user_id, entity_a_id, entity_b_id),
  FOREIGN KEY (entity_a_id) REFERENCES entities(id) ON DELETE CASCADE,
  FOREIGN KEY (entity_b_id) REFERENCES entities(id) ON DELETE CASCADE
);

-- Topic profiles — evolving user model per life-area topic.
-- Pattern borrowed from Memobase (Apache-2.0).
-- ADD-only semantics: user_profile sentences appended, never overwritten by AI.
CREATE TABLE IF NOT EXISTS topic_profiles (
  user_id TEXT NOT NULL,
  topic TEXT NOT NULL,                  -- canonical key e.g. "work", "family"
  user_profile TEXT NOT NULL DEFAULT '', -- AI-evolved description of user under this topic
  themes_json TEXT NOT NULL DEFAULT '[]', -- recurring patterns array
  mention_count INTEGER NOT NULL DEFAULT 0,
  last_updated TEXT,
  last_flushed TEXT,                    -- when profile was last regenerated by LLM
  pending_buffer TEXT NOT NULL DEFAULT '', -- entry summaries waiting next flush
  PRIMARY KEY (user_id, topic)
);
CREATE INDEX IF NOT EXISTS idx_topic_profiles_user ON topic_profiles(user_id);

-- Finalize packet queue per user: AI-summarized entries waiting for plugin to write to vault.
-- Plugin /pull returns these alongside messages.
CREATE TABLE IF NOT EXISTS finalize_packets (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT NOT NULL,
  date TEXT NOT NULL,
  topic TEXT,
  frontmatter_json TEXT NOT NULL,       -- mood, energy, people, places, projects, topics, tasks
  body TEXT NOT NULL,                    -- poetic line + narrative
  transcript_json TEXT NOT NULL DEFAULT '[]', -- ChatMessage[] for quote block
  photo_ids_json TEXT NOT NULL DEFAULT '[]', -- TG file_ids for photos to download
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_finalize_user ON finalize_packets(user_id, created_at);
